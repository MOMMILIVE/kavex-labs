import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'advertorial-app/package.json'));
const sharp = require('sharp');
const output = path.join(root, 'advertorial-app/public/advertorial/media');
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
const media = {};
for (const name of ['cad_design', 'gold_pour', 'hand_setting', 'editorial_bands', 'fancy_yellow']) {
  const source = readFileSync(path.join(root, 'assets', `${name}.webp`));
  const metadata = await sharp(source).metadata();
  const widths = name === 'cad_design' || name === 'gold_pour' ? [480, 768, metadata.width] : [192, 384, 640, metadata.width];
  const variants = [];
  for (const width of widths) {
    // Preserve the original bytes at full resolution; only downsize smaller candidates.
    const bytes = width >= metadata.width ? source : await sharp(source).resize({ width, withoutEnlargement: true }).webp({ quality: 85, effort: 6 }).toBuffer();
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    const filename = `${name}.${hash}.${width}.webp`;
    writeFileSync(path.join(output, filename), bytes);
    variants.push({ width, src: `/advertorial/media/${filename}`, bytes: bytes.length });
  }
  media[name] = { width: metadata.width, height: metadata.height, src: variants.at(-1).src, srcSet: variants.map(v => `${v.src} ${v.width}w`).join(', '), variants };
}
writeFileSync(path.join(root, 'advertorial-app/lib/media.ts'), `// Generated by scripts/optimize-advertorial-media.mjs from the original site assets.\nexport const media = ${JSON.stringify(media, null, 2)} as const;\n`);
console.log(JSON.stringify(Object.fromEntries(Object.entries(media).map(([name, m]) => [name, m.variants.map(v => ({ width: v.width, bytes: v.bytes }))])), null, 2));
